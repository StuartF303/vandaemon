"""
Embed src/web/index.html into the firmware as a PROGMEM raw string literal.

Runs as a PlatformIO pre-script (see platformio.ini extra_scripts) and writes
src/web_page.gen.h, which web.cpp includes. The page stays an ordinary HTML
file that a browser or tools/web_mock.py can open directly; the generated
header is a build artefact and is gitignored.

Only rewrites the header when the content changed, so an unchanged page does
not force web.cpp to recompile.
"""

import os

Import("env")  # noqa: F821  (injected by SCons)

DELIM = "VDWEB"
MAX_BYTES = 24000

project = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(project, "src", "web", "index.html")
dst = os.path.join(project, "src", "web_page.gen.h")

with open(src, "rb") as fh:
    raw = fh.read()

if len(raw) > MAX_BYTES:
    raise SystemExit(
        "embed_web: index.html is %d bytes, over the %d-byte budget" % (len(raw), MAX_BYTES)
    )
closing = (")" + DELIM + '"').encode()
if closing in raw:
    raise SystemExit("embed_web: index.html contains the raw-string delimiter %r" % closing)

text = raw.decode("utf-8")
header = (
    "// GENERATED by tools/embed_web.py from src/web/index.html -- do not edit.\n"
    "#pragma once\n"
    "#include <pgmspace.h>\n"
    "\n"
    'static const char WEB_PAGE[] PROGMEM = R"' + DELIM + "(" + text + ")" + DELIM + '";\n'
    "static const size_t WEB_PAGE_LEN = sizeof(WEB_PAGE) - 1;\n"
)

existing = None
if os.path.exists(dst):
    with open(dst, "r", encoding="utf-8", newline="") as fh:
        existing = fh.read()

if existing != header:
    with open(dst, "w", encoding="utf-8", newline="") as fh:
        fh.write(header)
    print("[embed-web] wrote %s (%d bytes of HTML)" % (os.path.relpath(dst, project), len(raw)))
else:
    print("[embed-web] %s up to date (%d bytes of HTML)" % (os.path.relpath(dst, project), len(raw)))
